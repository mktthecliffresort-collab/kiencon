/**
 * Builds merged leaderboard with the current user dynamically inserted and ranked
 */
export function getLeaderboardEntries(user: UserProfile, grade: GradeLevel): LeaderboardEntry[] {
  const baseList = grade === 5 ? INITIAL_LEADERBOARD_GRADE_5 : INITIAL_LEADERBOARD_GRADE_8;

  const currentUserEntry: LeaderboardEntry = {
    id: user.id,
    name: `${user.name || user.nickname || 'Bạn'} (Bạn)`,
    grade: user.grade,
    avatar: user.avatar || (user.grade === 5 ? '👦' : '🧑‍🎓'),
    school: user.grade === 5 ? 'Tiểu học Thực Nghiệm' : 'THCS Nguyễn Du',
    className: user.grade === 5 ? '5A3' : '8B1',
    xp: user.xp,
    streakDays: user.streakDays,
    lessonsCompletedCount: Math.max(user.completedLessons.length, user.grade === 5 ? 5 : 11),
    rankChange: 'up',
    rankChangeAmount: 1,
    badgeTitle: user.grade === 5 ? 'Kiến Thần Tốc' : 'Kỹ Sư Trẻ Tài Năng',
    cheersReceived: 18,
    isCurrentUser: true,
  };

  const allEntries: LeaderboardEntry[] = [...baseList.map((entry) => ({ ...entry, isCurrentUser: false })), currentUserEntry];

  // Sort descending by XP
  allEntries.sort((a, b) => b.xp - a.xp);

  return allEntries;
}
